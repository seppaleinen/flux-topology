"""Shared markdown rendering for app cards and queries."""

from __future__ import annotations


def render_markdown(data: dict) -> str:
    """Render an app card as markdown.

    Args:
        data: App data dict with keys like 'name', 'domain', 'path', 'id',
              'signals', 'workloads', 'services', 'ingress_hosts', 'edges',
              'warnings', 'crux', etc.

    Returns:
        Markdown-formatted string for the app card.
    """
    lines: list[str] = []

    # App header
    name = data.get("name", "unknown")
    lines.append(f"# App: {name}")
    lines.append("")

    # Metadata
    domain = data.get("domain", "")
    path = data.get("path", "")
    app_id = data.get("id", "")
    lines.append(f"- **Domain**: {domain}")
    lines.append(f"- **Path**: `{path}`")
    lines.append(f"- **ID**: `{app_id}`")
    if data.get("signals"):
        lines.append(f"- **Signals**: {', '.join(data['signals'])}")
    lines.append("")

    # Workloads
    if data.get("workloads"):
        lines.append("## Workloads")
        lines.append("")
        for w in data["workloads"]:
            replicas_str = f" (×{w['replicas']})" if w.get("replicas") is not None else ""
            lines.append(f"- {w['kind']}: {w['name']}{replicas_str}")
        lines.append("")

    # Services - no port in query version
    if data.get("services"):
        lines.append("## Services")
        lines.append("")
        for svc in data["services"]:
            ns_str = f" (ns: {svc['namespace']})" if svc.get("namespace") else ""
            lines.append(f"- {svc['name']}{ns_str}")
        lines.append("")

    # Flux objects
    if data.get("flux_objects"):
        lines.append("## Flux Objects")
        lines.append("")
        for fo in data["flux_objects"]:
            ns_str = f" (ns: {fo['namespace']})" if fo.get("namespace") else ""
            lines.append(f"- {fo['kind']}: {fo['name']}{ns_str}")
        lines.append("")

    # Ingress hosts
    if data.get("ingress_hosts"):
        lines.append("## Ingress Hosts")
        lines.append("")
        for h in data["ingress_hosts"]:
            lines.append(f"- `{h}`")
        lines.append("")

    # Crux: the handful of lines that carry the logic
    if data.get("crux"):
        lines.append("## Crux")
        lines.append("")
        for c in data["crux"]:
            lines.append(f"- {c}")
        lines.append("")

    # Edge sections: Depends On (all out-edges) and Referenced By (all in-edges)
    out_edges = data.get("edges_out", [])
    in_edges = data.get("edges_in", [])

    if out_edges:
        lines.append("## Depends On")
        lines.append("")
        for e in out_edges:
            lines.append(f"- **{e['to']}** ({e['type']}) — {e['evidence']}")
        lines.append("")

    if in_edges:
        lines.append("## Referenced By")
        lines.append("")
        for e in in_edges:
            lines.append(f"- **{e['from']}** ({e['type']}) — {e['evidence']}")
        lines.append("")

    # Encrypted flag
    if data.get("encrypted"):
        lines.append("## Encrypted")
        lines.append("")
        lines.append("Contains SOPS-encrypted secrets")
        lines.append("")

    # Warnings for this app
    app_warnings = data.get("warnings", [])
    if app_warnings:
        lines.append("## Warnings")
        lines.append("")
        for w in app_warnings:
            lines.append(f"- [{w['kind']}] {w['detail']}")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by flux-topology*")
    lines.append("")

    return "\n".join(lines)